export const VALE_STRINGS: Record<string, ValeStrings> = { en, zh };

/** The page's words in a language, English when the language has none of its own. */
export const valeStrings = (lang: string | undefined): ValeStrings => VALE_STRINGS[lang ?? "en"] ?? en;

/** "the True God" heads a line as "The True God"; scripts without capitals are left alone. */
export const capital = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
